"""Length arithmetic shared by Ming audio processors and model runners."""

from collections.abc import Iterable


def conv_output_length(length: int, kernel: int, stride: int, padding: int) -> int:
    """Return the output length of a non-dilated 1-D convolution."""
    if length < 0:
        raise ValueError(f"Input length must be non-negative, got {length}")
    if kernel <= 0 or stride <= 0 or padding < 0:
        raise ValueError("Invalid convolution parameters")
    return max(0, (length + 2 * padding - kernel) // stride + 1)


def apply_conv_stack(
    length: int,
    kernels: Iterable[int],
    strides: Iterable[int],
    paddings: Iterable[int],
) -> int:
    """Apply a sequence of 1-D convolution length transforms."""
    kernels = tuple(kernels)
    strides = tuple(strides)
    paddings = tuple(paddings)
    if not (len(kernels) == len(strides) == len(paddings)):
        raise ValueError("Convolution parameter lists must have equal length")
    for kernel, stride, padding in zip(kernels, strides, paddings, strict=True):
        length = conv_output_length(length, kernel, stride, padding)
    return length


def iter_chunk_lengths(length: int, chunk_size: int) -> tuple[int, ...]:
    """Split a logical feature length into the checkpoint's Whisper chunks."""
    if length < 0:
        raise ValueError(f"Input length must be non-negative, got {length}")
    if chunk_size <= 0:
        raise ValueError(f"Chunk size must be positive, got {chunk_size}")
    if length == 0:
        return ()
    full_chunks, remainder = divmod(length, chunk_size)
    return (chunk_size,) * full_chunks + ((remainder,) if remainder else ())


def whisper_output_length(length: int) -> int:
    """Length after Ming's Whisper conv1(s=1) and conv2(s=2)."""
    length = conv_output_length(length, kernel=3, stride=1, padding=1)
    return conv_output_length(length, kernel=3, stride=2, padding=1)


def ming3_projected_chunk_length(
    chunk_length: int,
    kernels: Iterable[int],
    strides: Iterable[int],
    paddings: Iterable[int],
) -> int:
    """Projected token count for one pre-projector mel chunk."""
    return apply_conv_stack(whisper_output_length(chunk_length), kernels, strides, paddings)


def ming3_audio_token_count(
    mel_length: int,
    *,
    chunk_size: int,
    kernels: Iterable[int],
    strides: Iterable[int],
    paddings: Iterable[int],
) -> int:
    """Exact number of audio placeholders generated by Ming-3.0."""
    return sum(
        ming3_projected_chunk_length(length, kernels, strides, paddings)
        for length in iter_chunk_lengths(mel_length, chunk_size)
    )


def max_mel_frames_for_audio_tokens(
    max_tokens: int,
    *,
    chunk_size: int,
    kernels: Iterable[int],
    strides: Iterable[int],
    paddings: Iterable[int],
) -> int:
    """Largest mel length whose projected representation fits a token budget."""
    if max_tokens <= 0:
        return 0

    def count(length: int) -> int:
        return ming3_audio_token_count(
            length,
            chunk_size=chunk_size,
            kernels=kernels,
            strides=strides,
            paddings=paddings,
        )

    # Downsampling is monotonic. Grow a bound first, then find the exact
    # maximum without duplicating the convolution/chunk arithmetic.
    low, high = 0, max_tokens * 2
    while count(high) <= max_tokens:
        low, high = high, high * 2
    while low + 1 < high:
        middle = (low + high) // 2
        if count(middle) <= max_tokens:
            low = middle
        else:
            high = middle
    return low
