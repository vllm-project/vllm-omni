QTYPE = "W4A4_MXFP4"
EXPERTS = ("high_noise_model", "low_noise_model")
TARGETS = ("transformer", "transformer_2")
QUANT_FILE = "quant_model_weight_w4a4_mxfp4.safetensors"
DESC_FILE = "quant_model_description_w4a4_mxfp4.json"


def _json(path, value):
    path.write_text(json.dumps(value), encoding="utf-8")


def _fixture(tmp_path, smooth=False):
    """Tiny native Wan names, official uint8 export packing and two distinct experts."""
    original, quant, output = (tmp_path / name for name in ("original", "quant", "output"))
    original.mkdir()
    quant.mkdir()
    _json(
        original / "model_index.json",
        {
            "_class_name": "WanPipeline",
            "transformer": ["diffusers", "WanTransformer3DModel"],
            "transformer_2": ["diffusers", "WanTransformer3DModel"],
        },
    )
    (original / "tokenizer").mkdir()
    (original / "tokenizer/vocab.txt").write_text("unchanged scaffold", encoding="utf-8")
    # Source/target pairs are independently specified, not generated by production remapping.
    pairs = [
        ("blocks.0.self_attn.q", "blocks.0.attn1.to_q"),
        ("blocks.0.self_attn.k", "blocks.0.attn1.to_k"),
        ("blocks.0.self_attn.v", "blocks.0.attn1.to_v"),
        ("blocks.0.self_attn.o", "blocks.0.attn1.to_out.0"),
        ("blocks.0.ffn.0", "blocks.0.ffn.net.0.proj"),
        ("blocks.0.ffn.2", "blocks.0.ffn.net.2"),
        ("blocks.0.cross_attn.q", "blocks.0.attn2.to_q"),
    ]
    float_pairs = [
        ("blocks.1.self_attn.q", "blocks.1.attn1.to_q"),
        ("blocks.1.self_attn.k", "blocks.1.attn1.to_k"),
        ("blocks.1.self_attn.v", "blocks.1.attn1.to_v"),
        ("blocks.1.self_attn.o", "blocks.1.attn1.to_out.0"),
        ("blocks.1.ffn.0", "blocks.1.ffn.net.0.proj"),
        ("blocks.1.ffn.2", "blocks.1.ffn.net.2"),
        ("blocks.1.cross_attn.k", "blocks.1.attn2.to_k"),
        ("head.head", "proj_out"),
        ("time_embedding.0", "condition_embedder.time_embedder.linear_1"),
    ]
    for index, (source, target) in enumerate(zip(EXPERTS, TARGETS)):
        src, base = quant / source, original / target
        src.mkdir()
        base.mkdir()
        _json(base / "config.json", {"_class_name": "WanTransformer3DModel", "num_layers": 2})
        raw, desc, bf16 = {}, {"model_quant_type": QTYPE}, {}
        # Each row covers both signs and every E2M1 value, including negative zero.
        pattern = [0x10, 0x32, 0x54, 0x76, 0x98, 0xBA, 0xDC, 0xFE]
        if index:
            pattern = list(reversed(pattern))
        for native, diffusers in pairs:
            prefix = native + (".linear" if smooth else "")
            raw[prefix + ".weight"] = torch.tensor(pattern * 16, dtype=torch.uint8).reshape(4, 32)
            raw[prefix + ".weight_scale"] = torch.tensor([126, 128] * 4, dtype=torch.uint8).reshape(4, 2)
            raw[prefix + ".bias"] = torch.arange(4, dtype=torch.float32) + index
            desc[prefix + ".weight"] = desc[prefix + ".weight_scale"] = QTYPE
            desc[prefix + ".bias"] = "FLOAT"
            bf16[diffusers + ".weight"] = torch.full((4, 64), 9, dtype=torch.bfloat16)
            bf16[diffusers + ".bias"] = torch.full((4,), 9, dtype=torch.bfloat16)
            if smooth:
                raw[native + ".div.mul_scale"] = torch.linspace(0.5, 1.5, 64)
                desc[native + ".div.mul_scale"] = "FLOAT"
        for native, diffusers in float_pairs:
            raw[native + ".weight"] = torch.full((4, 64), index + 3, dtype=torch.bfloat16)
            bf16[diffusers + ".weight"] = torch.full((4, 64), 9, dtype=torch.bfloat16)
            desc[native + ".weight"] = "FLOAT"
        for native, diffusers in (
            ("blocks.0.norm2.weight", "blocks.0.norm3.weight"),
            ("blocks.0.modulation", "blocks.0.scale_shift_table"),
        ):
            raw[native] = torch.ones(4, dtype=torch.bfloat16)
            bf16[diffusers] = torch.zeros(4, dtype=torch.bfloat16)
            desc[native] = "FLOAT"
        # Non-Linear scaffold can come only from the original without quant metadata.
        bf16["patch_embedding.weight"] = torch.zeros((4, 16, 1, 2, 2), dtype=torch.bfloat16)
        save_file(bf16, str(base / "diffusion_pytorch_model.safetensors"))
        save_file(raw, str(src / QUANT_FILE))
        _json(src / DESC_FILE, desc)
    return original, quant, output


def _convert(paths, **kwargs):
    return converter.repack("Wan2.2-T2V-A14B", *paths, **kwargs)


def _read_output(directory):
    result = {}
    for path in directory.glob("*.safetensors"):
        result.update(load_file(str(path)))
    return result


def _edit(paths, mutate, expert=1):
    directory = paths[1] / EXPERTS[expert]
    raw = load_file(str(directory / QUANT_FILE))
    desc = json.loads((directory / DESC_FILE).read_text(encoding="utf-8"))
    mutate(raw, desc)
    save_file(raw, str(directory / QUANT_FILE))
    _json(directory / DESC_FILE, desc)


@pytest.mark.parametrize("smooth", [False, True])
def test_real_two_expert_conversion_preserves_values_scales_and_policy(tmp_path, smooth):
    paths = _fixture(tmp_path, smooth)
    report = _convert(paths, max_shard_bytes=2048)
    original, quant, output = paths
    expected = [0, 0.5, 1, 1.5, 2, 3, 4, 6, -0.0, -0.5, -1, -1.5, -2, -3, -4, -6]
    for index, target in enumerate(TARGETS):
        state = _read_output(output / target)
        config = json.loads((output / target / "config.json").read_text())
        policy = config["quantization_config"]
        assert policy["quant_method"] == "mxfp4"
        assert policy["is_checkpoint_mxfp4_serialized"] is True
        assert policy["require_smooth_scale"] is smooth
        assert "is_checkpoint_serialized" not in policy
        assert {
            "blocks.1.attn1.to_qkv",
            "blocks.1.attn1.to_out",
            "blocks.1.ffn.net_0.proj",
            "blocks.1.ffn.net_2",
            "blocks.1.attn2.to_k",
            "proj_out",
            "condition_embedder.time_embedder.linear_1",
        } <= set(policy["ignored_layers"])
        assert "blocks.0.attn1.to_qkv" not in policy["ignored_layers"]
        row = expected if not index else sum([expected[i : i + 2] for i in range(14, -1, -2)], [])
        expected_weight = torch.tensor(row * 16, dtype=torch.bfloat16).reshape(4, 64)
        weight = state["blocks.0.attn1.to_q.weight"]
        assert weight.dtype == torch.bfloat16
        assert torch.equal(weight, expected_weight)
        assert torch.equal(torch.signbit(weight), torch.signbit(expected_weight))
        raw = load_file(str(quant / EXPERTS[index] / QUANT_FILE))
        prefix = "blocks.0.self_attn.q" + (".linear" if smooth else "")
        scale = state["blocks.0.attn1.to_q.weight_scale"]
        assert scale.dtype == torch.uint8
        assert torch.equal(scale, raw[prefix + ".weight_scale"])
        assert torch.equal(state["blocks.0.attn1.to_q.bias"], raw[prefix + ".bias"])
        assert bool((state["blocks.1.attn1.to_q.weight"] == index + 3).all())
        assert bool((state["blocks.0.norm3.weight"] == 1).all())
        if smooth:
            assert torch.equal(state["blocks.0.attn1.to_q.mul_scale"], raw["blocks.0.self_attn.q.div.mul_scale"])
        else:
            assert not any(name.endswith("mul_scale") for name in state)
            assert "does not validate Smooth" in report["experts"][target]["smooth"]
        assert not any("dual_scale" in name or "w4a8_weight" in name for name in state)
        index_json = json.loads((output / target / "diffusion_pytorch_model.safetensors.index.json").read_text())
        assert set(index_json["weight_map"]) == set(state)
        assert len(set(index_json["weight_map"].values())) > 1
        for name, shard in index_json["weight_map"].items():
            with safe_open(str(output / target / shard), framework="pt") as archive:
                assert name in archive.keys()
    assert (output / "tokenizer/vocab.txt").read_bytes() == (original / "tokenizer/vocab.txt").read_bytes()
    assert report == json.loads((output / "mxfp4_conversion_report.json").read_text(encoding="utf-8"))
    assert report["producer_version"].startswith("unknown")
    assert "not verified" in report["algorithm_provenance"]


