def test_all_e2m1_codes_and_nibble_order_via_real_files(tmp_path):
    paths = _fixture(tmp_path)

    # Two independent source tensors together cover all 256 possible packed bytes.
    def all_codes(raw, desc):
        raw["blocks.0.ffn.0.weight"] = torch.arange(128, dtype=torch.uint8).reshape(4, 32)
        raw["blocks.0.ffn.2.weight"] = torch.arange(128, 256, dtype=torch.uint8).reshape(4, 32)

    _edit(paths, all_codes)
    _convert(paths)
    result = _read_output(paths[2] / "transformer_2")

    # Scalar E2M1 definition is independent of the production lookup table.
    def scalar(code):
        exponent, mantissa = (code >> 1) & 3, code & 1
        magnitude = mantissa / 2 if exponent == 0 else (1 + mantissa / 2) * 2 ** (exponent - 1)
        return -magnitude if code & 8 else magnitude

    for target, start in (("blocks.0.ffn.net.0.proj.weight", 0), ("blocks.0.ffn.net.2.weight", 128)):
        expected = torch.tensor(
            [scalar(code) for byte in range(start, start + 128) for code in (byte & 15, byte >> 4)],
            dtype=torch.bfloat16,
        ).reshape(4, 64)
        assert torch.equal(result[target], expected)
        assert torch.equal(torch.signbit(result[target]), torch.signbit(expected))


