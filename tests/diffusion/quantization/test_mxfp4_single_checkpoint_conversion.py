@pytest.mark.parametrize(
    "case,match",
    [
        ("missing_weight", "缺少量化 tensor"),
        ("missing_scale", "缺少量化 tensor"),
        ("missing_weight_label", "缺量化描述"),
        ("omitted_layer", "Linear 缺量化描述"),
        ("wrong_weight_dtype", "weight packing"),
        ("wrong_weight_shape", "weight packing"),
        ("wrong_scale_dtype", "weight_scale 必须"),
        ("wrong_scale_shape", "weight_scale 必须"),
        ("scale_nan", "E8M0 NaN"),
        ("dual_scale", "无原模型映射"),
        ("orphan_scale", "孤立/非法 weight_scale"),
        ("missing_bias", "缺导出 bias"),
        ("wrong_bias_shape", "FLOAT tensor dtype/shape"),
        ("nan_bias", "bias 必须"),
        ("global_dual", "model_quant_type"),
        ("missing_global", "model_quant_type"),
        ("fa_metadata", "不支持"),
        ("rotation_float", "不支持"),
        ("unknown_float", "不支持"),
        ("int_float", "FLOAT tensor dtype/shape"),
        ("wrong_group", "group_size"),
        ("partial_qkv", "QKV 不允许部分"),
    ],
)
def test_malformed_real_checkpoint_fails_without_publishing(tmp_path, case, match):
    paths = _fixture(tmp_path)

    def mutate(raw, desc):
        key = "blocks.0.ffn.0.weight"
        scale = "blocks.0.ffn.0.weight_scale"
        bias = "blocks.0.ffn.0.bias"
        if case == "missing_weight":
            del raw[key]
        elif case == "missing_scale":
            del raw[scale]
        elif case == "missing_weight_label":
            del desc[key]
        elif case == "omitted_layer":
            for name in (key, scale, bias):
                del raw[name], desc[name]
        elif case == "wrong_weight_dtype":
            raw[key] = raw[key].to(torch.int8)
        elif case == "wrong_weight_shape":
            raw[key] = raw[key][:, :16].contiguous()
        elif case == "wrong_scale_dtype":
            raw[scale] = raw[scale].float()
        elif case == "wrong_scale_shape":
            raw[scale] = raw[scale].reshape(4, 1, 2)
        elif case == "scale_nan":
            raw[scale][0, 0] = 255
        elif case in ("dual_scale", "orphan_scale", "rotation_float", "unknown_float"):
            name = {
                "dual_scale": "blocks.0.ffn.0.weight_dual_scale",
                "orphan_scale": "blocks.1.ffn.0.weight_scale",
                "rotation_float": "blocks.0.self_attn.q.rotation",
                "unknown_float": "other_recipe.cache",
            }[case]
            raw[name] = torch.ones(4)
            desc[name] = "FLOAT"
        elif case == "missing_bias":
            del raw[bias], desc[bias]
        elif case == "wrong_bias_shape":
            raw[bias] = torch.zeros(5)
        elif case == "nan_bias":
            raw[bias][0] = float("nan")
        elif case == "global_dual":
            desc["model_quant_type"] = "W4A4_MXFP4_DUALSCALE"
        elif case == "missing_global":
            del desc["model_quant_type"]
        elif case == "fa_metadata":
            desc["blocks.0.self_attn.quant_type"] = "MXFP4_DYNAMIC"
        elif case == "int_float":
            raw["head.head.weight"] = raw["head.head.weight"].to(torch.int8)
        elif case == "wrong_group":
            desc["group_size"] = 64
        elif case == "partial_qkv":
            name = "blocks.0.self_attn.q"
            raw[name + ".weight"] = torch.zeros((4, 64), dtype=torch.bfloat16)
            desc[name + ".weight"] = "FLOAT"
            del raw[name + ".weight_scale"], desc[name + ".weight_scale"]

    _edit(paths, mutate)
    with pytest.raises(ValueError, match=match):
        _convert(paths)
    assert not paths[2].exists()
    assert not list(tmp_path.glob(".mxfp4-import-*"))


