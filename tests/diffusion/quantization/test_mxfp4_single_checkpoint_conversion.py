def test_smooth_contract_is_strict(tmp_path, case, match):
    paths = _fixture(tmp_path, smooth=True)

    def mutate(raw, desc):
        key = "blocks.0.self_attn.q.div.mul_scale"
        if case == "missing":
            del raw[key]
