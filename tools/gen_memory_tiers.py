"""Render the documented minimum-memory index from structured recipes.

The structured recipe sources under ``recipes/models/`` already record a
per-variant minimum device memory (``variants.<name>.vram_minimum_gb``). This
tool turns them into one page so a user can answer "what is documented to run
on my device?" before downloading weights, and so downstream consumers can read
the same numbers as JSON instead of parsing prose.

Usage:
    python tools/gen_memory_tiers.py                    # write both artifacts
    python tools/gen_memory_tiers.py --check            # fail if it is stale
    python tools/gen_memory_tiers.py --format json      # machine-readable
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RECIPES_DIR = REPO_ROOT / "recipes" / "models"
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "models" / "memory_tiers.md"
# Packaged copy: `vllm-omni doctor` reads the same numbers as the docs page.
DEFAULT_JSON_OUTPUT = REPO_ROOT / "vllm_omni" / "utils" / "memory_tiers.json"

# Tiers a consumer device is expected to land in. Only used to group the
# rendered page; the numbers themselves come from the recipes.
TIERS = (8, 12, 16, 24)

# A few structured recipes encode tasks as bare ids instead of labelled
# mappings; keep the rendered column consistent without guessing new ids.
TASK_LABELS = {"t2i": "Text-to-image", "i2i": "Image-to-image", "t2a": "Text-to-audio"}

GENERATED_NOTE = (
    "<!-- Generated by tools/gen_memory_tiers.py from recipes/models/**. "
    "Do not edit by hand; regenerate instead. -->"
)


@dataclass(frozen=True)
class Variant:
    """One documented deployment variant of one model."""

    model_id: str
    provider: str
    variant: str
    minimum_gib: int
    precision: str
    tasks: tuple[str, ...]
    source: str

    def sort_key(self) -> tuple[int, str, str]:
        return (self.minimum_gib, self.model_id, self.variant)

    def as_dict(self) -> dict[str, Any]:
        return {
            "model_id": self.model_id,
            "provider": self.provider,
            "variant": self.variant,
            "minimum_gib": self.minimum_gib,
            "precision": self.precision,
            "tasks": list(self.tasks),
            "source": self.source,
        }


def _task_labels(data: dict[str, Any]) -> tuple[str, ...]:
    """Task labels for display; ``omni.tasks`` entries are str or mapping."""
    omni = data.get("omni") or {}
    labels: list[str] = []
    for task in omni.get("tasks") or []:
        if isinstance(task, str):
            labels.append(TASK_LABELS.get(task, task))
        elif task.get("label"):
            labels.append(str(task["label"]))
        elif task.get("id"):
            labels.append(TASK_LABELS.get(str(task["id"]), str(task["id"])))
    if labels:
        return tuple(labels)
    meta = data.get("meta") or {}
    return tuple(TASK_LABELS.get(str(task), str(task)) for task in meta.get("tasks") or [])


def _precision(value: Any) -> str:
    return str(value) if value else "-"


def load_variants(recipes_dir: Path) -> tuple[list[Variant], list[Path]]:
    """Collect every variant that declares a minimum device memory.

    Returns the variants plus every source file that was read, so callers can
    report how much of the recipe tree is machine-readable.
    """
    sources = sorted(recipes_dir.rglob("*.yaml"))
    variants: list[Variant] = []
    for path in sources:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not isinstance(data, dict):
            raise ValueError(f"{path}: expected a mapping at the top level")
        model = data.get("model") or {}
        meta = data.get("meta") or {}
        model_id = model.get("model_id") or meta.get("slug")
        if not model_id:
            raise ValueError(f"{path}: missing model.model_id")
        provider = str(meta.get("provider") or "")
        tasks = _task_labels(data)
        for name, variant in (data.get("variants") or {}).items():
            minimum = (variant or {}).get("vram_minimum_gb")
            if minimum is None:
                continue
            variants.append(
                Variant(
                    model_id=str((variant or {}).get("model_id") or model_id),
                    provider=provider,
                    variant=str(name),
                    minimum_gib=int(minimum),
                    precision=_precision((variant or {}).get("precision")),
                    tasks=tasks,
                    source=str(path.relative_to(recipes_dir.parent.parent)),
                )
            )
    variants.sort(key=Variant.sort_key)
    return variants, sources


def _render_tier_section(variants: list[Variant]) -> list[str]:
    """Group variants into tiers, listing only the ones new to each tier."""
    lines: list[str] = []
    previous = 0
    for tier in TIERS:
        new = [variant for variant in variants if previous < variant.minimum_gib <= tier]
        total = sum(1 for variant in variants if variant.minimum_gib <= tier)
        lines.append(f"### {tier} GiB")
        lines.append("")
        if not total:
            lines.append("No recipe documents a minimum at or below this tier.")
            lines.append("")
            previous = tier
            continue
        if not new:
            lines.append(
                f"No variant documents a minimum in this band; {total} already fit at {previous} GiB or below."
            )
        elif previous:
            lines.append(f"{total} variants documented at or below this tier; {len(new)} first fit here.")
        else:
            lines.append(f"{total} variants documented at or below this tier.")
        if new:
            lines.append("")
            for variant in new:
                tasks = ", ".join(variant.tasks) or "-"
                lines.append(
                    f"- `{variant.model_id}` ({variant.variant}, needs {variant.minimum_gib} GiB,"
                    f" {variant.precision}) - {tasks}"
                )
        lines.append("")
        previous = tier
    return lines


def render(
    variants: list[Variant],
    source_count: int,
    markdown_recipe_count: int,
) -> str:
    models = {variant.model_id for variant in variants}
    lines = [
        "# Minimum Memory Tiers",
        "",
        GENERATED_NOTE,
        "",
        "This page lists the minimum device memory each structured recipe declares",
        "for its deployment variants. Use it to check whether a model is documented",
        "for your device before downloading weights or starting servers.",
        "",
        "!!! note",
        "    A value here is the minimum that a recipe documents for a variant; it",
        "    is not a promise that every configuration fits, and it is not a",
        "    measured peak for your exact workload. A device below a documented",
        "    minimum is **not yet measured**, not unsupported. Tiers without a",
        "    documented recipe have no evidence either way.",
        "",
        "## Coverage",
        "",
        f"- {len(variants)} variants of {len(models)} models declare a minimum device memory.",
        f"- {source_count} structured recipe sources were read from `recipes/models/`.",
        f"- {markdown_recipe_count} Markdown recipes are free-form prose and are not indexed here;",
        "  they remain the source of truth for commands and qualification evidence.",
        "",
        "Run `vllm-omni doctor` to compare your machine against this index.",
        "",
        "Regenerate with `python tools/gen_memory_tiers.py`.",
        "",
        "## By consumer tier",
        "",
        "Each variant appears under the first tier whose memory it fits.",
        "",
        *_render_tier_section(variants),
        "## All documented minimums",
        "",
        "| Min memory (GiB) | Model | Variant | Precision | Tasks | Source |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for variant in variants:
        tasks = ", ".join(variant.tasks) or "-"
        lines.append(
            f"| {variant.minimum_gib} | `{variant.model_id}` | {variant.variant} |"
            f" {variant.precision} | {tasks} | <gh-file:{variant.source}> |"
        )
    lines.append("")
    return "\n".join(lines)


def build(
    recipes_dir: Path = DEFAULT_RECIPES_DIR,
    recipes_root: Path | None = None,
) -> tuple[str, list[Variant]]:
    recipes_root = recipes_root or recipes_dir.parent.parent
    variants, sources = load_variants(recipes_dir)
    markdown_recipe_count = sum(
        1
        for path in (recipes_root / "recipes").rglob("*.md")
        if path.name not in {"README.md", "TEMPLATE.md"}
    )
    return render(variants, len(sources), markdown_recipe_count), variants


def render_json(variants: list[Variant]) -> str:
    """Stable machine-readable form consumed by the CLI and by scripts."""
    return json.dumps([variant.as_dict() for variant in variants], indent=2) + "\n"


def create_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--recipes-dir", type=Path, default=DEFAULT_RECIPES_DIR, help="structured recipe sources")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Markdown page to write")
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON_OUTPUT, help="Packaged JSON to write")
    parser.add_argument("--format", choices=("markdown", "json"), default="markdown")
    parser.add_argument("--check", action="store_true", help="exit 1 when --output is out of date")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = create_parser().parse_args(argv)
    page, variants = build(args.recipes_dir)

    if args.format == "json":
        print(json.dumps([variant.as_dict() for variant in variants], indent=2))
        return 0

    artifacts = ((args.output, page), (args.json_output, render_json(variants)))

    if args.check:
        stale = [
            path for path, expected in artifacts if not path.exists() or path.read_text(encoding="utf-8") != expected
        ]
        if stale:
            for path in stale:
                print(f"{path} is out of date; run: python tools/gen_memory_tiers.py", file=sys.stderr)
            return 1
        print("generated artifacts are up to date")
        return 0

    for path, content in artifacts:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    print(f"{len(variants)} variants")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
