import argparse
import json
from datetime import datetime
from pathlib import Path
from typing import Dict, List


def load_benchmark(file_path: str) -> Dict:
    """加载基准测试结果"""
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)


def generate_comparison_report(current: Dict, baseline: Dict) -> str:
    """生成对比报告"""
    current_stats = current['statistics']
    baseline_stats = baseline['statistics']
    
    # 计算各项指标的变化
    avg_change = current_stats['average_latency_seconds'] - baseline_stats['average_latency_seconds']
    avg_change_percent = (avg_change / baseline_stats['average_latency_seconds']) * 100
    
    total_change = current_stats['total_latency_seconds'] - baseline_stats['total_latency_seconds']
    total_change_percent = (total_change / baseline_stats['total_latency_seconds']) * 100
    
    # 判断性能提升还是下降
    if avg_change_percent < -5:
        status = "🟢 IMPROVED"
        status_emoji = "📈"
    elif avg_change_percent > 5:
        status = "🔴 DEGRADED"
        status_emoji = "📉"
    else:
        status = "🟡 STABLE"
        status_emoji = "➡️"
    
    report = f"""# HunYuanImage 性能对比报告

{status_emoji} **状态**: {status}

## 测试配置对比

| 配置项 | 基线 | 当前 |
|--------|------|------|
| 模型 | {baseline.get('model', 'N/A')} | {current.get('model', 'N/A')} |
| Tensor Parallel | {baseline.get('tensor_parallel_size', 'N/A')} | {current.get('tensor_parallel_size', 'N/A')} |
| Expert Parallel | {baseline.get('expert_parallel_size', 'N/A')} | {current.get('expert_parallel_size', 'N/A')} |
| 推理步数 | {baseline.get('num_inference_steps', 'N/A')} | {current.get('num_inference_steps', 'N/A')} |
| 引导系数 | {baseline.get('guidance_scale', 'N/A')} | {current.get('guidance_scale', 'N/A')} |

## 性能指标对比

### 平均延迟

| 指标 | 基线 | 当前 | 变化 |
|------|------|------|------|
| 平均延迟 | {baseline_stats['average_latency_seconds']:.2f}s | {current_stats['average_latency_seconds']:.2f}s | {avg_change:+.2f}s ({avg_change_percent:+.2f}%) |

### 总体性能

| 指标 | 基线 | 当前 | 变化 |
|------|------|------|------|
| 总延迟 | {baseline_stats['total_latency_seconds']:.2f}s | {current_stats['total_latency_seconds']:.2f}s | {total_change:+.2f}s ({total_change_percent:+.2f}%) |
| 测试样本数 | {baseline_stats['total_prompts']} | {current_stats['total_prompts']} | - |
| 最小延迟 | {baseline_stats['min_latency_seconds']:.2f}s | {current_stats['min_latency_seconds']:.2f}s | {current_stats['min_latency_seconds'] - baseline_stats['min_latency_seconds']:+.2f}s |
| 最大延迟 | {baseline_stats['max_latency_seconds']:.2f}s | {current_stats['max_latency_seconds']:.2f}s | {current_stats['max_latency_seconds'] - baseline_stats['max_latency_seconds']:+.2f}s |

## 详细对比

### 各提示词延迟对比

| # | 基线延迟 | 当前延迟 | 变化 |
|---|---------|---------|------|
"""
    
    # 添加详细对比（如果基线有详细数据）
    baseline_prompts = baseline.get('prompts', [])
    current_prompts = current.get('prompts', [])
    
    for i, (base_prompt, curr_prompt) in enumerate(zip(baseline_prompts, current_prompts), 1):
        change = curr_prompt['latency_seconds'] - base_prompt['latency_seconds']
        change_percent = (change / base_prompt['latency_seconds']) * 100
        report += f"| {i} | {base_prompt['latency_seconds']:.2f}s | {curr_prompt['latency_seconds']:.2f}s | {change:+.2f}s ({change_percent:+.2f}%) |\n"
    
    report += f"""
## 优化建议

"""
    
    if avg_change_percent > 10:
        report += """⚠️ **性能下降超过 10%，建议检查以下方面：**

1. **代码变更** - 检查最近的提交是否引入了性能回退
2. **环境配置** - 确认 GPU 驱动、CUDA 版本等是否正确
3. **硬件状态** - 检查 GPU 是否正常运行，有无降频
4. **负载情况** - 确认测试时是否有其他任务占用资源
"""
    elif avg_change_percent < -10:
        report += """✅ **性能提升超过 10%，优化效果显著！**

可能的优化来源：
1. **代码优化** - 最近的提交可能包含了性能改进
2. **配置优化** - Tensor/Expert Parallel 配置可能更合理
3. **环境优化** - 驱动或库版本升级可能带来性能提升

建议：
- 分析具体优化点，总结经验
- 考虑将优化应用到其他模块
"""
    else:
        report += """✅ **性能稳定，变化在正常范围内**

当前性能与基线基本一致，可以继续开发。

建议：
- 定期更新基线（建议每月一次）
- 关注长期性能趋势
"""
    
    report += f"""
---

**生成时间**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
**基线时间**: {baseline.get('timestamp', 'N/A')}
**当前时间**: {current.get('timestamp', 'N/A')}

*Generated by HunYuanImage Performance Dashboard*
"""
    
    return report


def main():
    parser = argparse.ArgumentParser(description='Compare benchmark results')
    parser.add_argument('--current', type=str, required=True, help='Current benchmark JSON file (can use glob pattern)')
    parser.add_argument('--baseline', type=str, required=True, help='Baseline benchmark JSON file')
    parser.add_argument('--output', type=str, default='comparison_report.md', help='Output markdown file')
    
    args = parser.parse_args()
    
    # 加载基准测试结果
    current = load_benchmark(args.current)
    baseline = load_benchmark(args.baseline)
    
    # 生成对比报告
    report = generate_comparison_report(current, baseline)
    
    # 保存报告
    output_path = Path(args.output)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(report)
    
    print(f"Comparison report saved to: {output_path}")
    print()
    print("=" * 70)
    print(report[:500])  # 打印前 500 字符
    print("...")
    print("=" * 70)


if __name__ == '__main__':
    main()
